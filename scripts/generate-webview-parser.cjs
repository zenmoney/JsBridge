// Run with Acorn 8.15.0 and Terser 5.44.0 installed (e.g. in a temporary directory).
// NODE_PATH=/tmp/jsbridge-parser/node_modules node scripts/generate-webview-parser.cjs
const fs = require('fs');
const acornPackage = require.resolve('acorn/package.json');
const path = require('path');
const acornRoot = path.dirname(acornPackage);
if (require(acornPackage).version !== '8.15.0' || require('terser/package.json').version !== '5.44.0') {
  throw new Error('Install the pinned Acorn 8.15.0 and Terser 5.44.0 versions before generating.');
}
(async () => {
  const original = fs.readFileSync(path.join(acornRoot, 'dist/acorn.js'), 'utf8');
  // A local CommonJS export keeps the parser private, regardless of the page's module globals.
  const source = 'function () { const exports = {}; const module = { exports };\n' + original + '\nreturn exports.parse; }';
  const { code } = await require('terser').minify('(' + source + ')', { compress: false, mangle: true, format: { comments: false, ascii_only: true } });
  const expression = code.replace(/;$/, '');
  const chunks = expression.match(/[\s\S]{1,8000}/g).map(s => '        ' + JSON.stringify(s).replace(/\$/g, '\\$') + ',');
  const license = fs.readFileSync(path.join(acornRoot, 'LICENSE'), 'utf8');
  const header = '// Generated by scripts/generate-webview-parser.cjs. Acorn 8.15.0, MIT license.\n// ' + license.trim().split('\n').map(line => line.trimEnd()).join('\n// ').replace(/ \n/g, '\n') + '\n';
  fs.writeFileSync('src/commonMain/kotlin/app/zenmoney/jsbridge/JsWebViewAcorn.kt',
    '@file:Suppress("ktlint:standard:max-line-length")\n\n' + header + '\npackage app.zenmoney.jsbridge\n\ninternal val jsWebViewAcornFactorySource: String =\n    listOf(\n' + chunks.join('\n') + '\n    ).joinToString("")\n');
  console.log('Parser size:', expression.length);
})();
